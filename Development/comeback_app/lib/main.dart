import 'package:flutter/material.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_crashlytics/firebase_crashlytics.dart';
import 'app/app.dart';
import 'firebase_options.dart'; // Generated by flutterfire configure

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // 0. Initialize Firebase & Crashlytics FIRST so we catch every error.
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  // [CRASHLYTICS] In debug mode, force-enable collection so test crashes reach the console.
  // In release, this is already enabled by default. This block only runs in debug.
  if (kDebugMode) {
    await FirebaseCrashlytics.instance.setCrashlyticsCollectionEnabled(true);
  }

  // [CRASHLYTICS] Catch Flutter framework errors (widget build errors, assertions, etc.)
  FlutterError.onError = (errorDetails) {
    FirebaseCrashlytics.instance.recordFlutterFatalError(errorDetails);
  };

  // [CRASHLYTICS] Catch asynchronous errors that escape the Flutter framework.
  // This is critical for errors from async code, Futures, and Streams.
  PlatformDispatcher.instance.onError = (error, stack) {
    FirebaseCrashlytics.instance.recordError(error, stack, fatal: true);
    return true;
  };

  // 1. Initialize Supabase
  await Supabase.initialize(
    url: 'https://isiggphtpfrmxyosnhzc.supabase.co', 
    // Use the Publishable key (or the legacy anon key)
    publishableKey: 'sb_publishable_AtjjW81lUvI0c-QWqJZwxw_HFLA6mtF', 
  );

  // 2. Enforce Portrait Mode
  await SystemChrome.setPreferredOrientations(const [
    DeviceOrientation.portraitUp,
    DeviceOrientation.portraitDown,
  ]);

  // 3. Run the App
  runApp(const ComebakApp());
}